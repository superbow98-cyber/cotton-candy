// --------- Markdown export ---------
export function lectureToMarkdown(l: Lecture): string {
  const lines: string[] = []
  const date = new Date(l.started_at).toLocaleString()
  lines.push(`# ${l.title}`, '')
  if (l.subject)  lines.push(`**Subject:** ${l.subject}  `)
  if (l.lecturer) lines.push(`**Lecturer:** ${l.lecturer}  `)
  if (l.location) lines.push(`**Location:** ${l.location}  `)
  lines.push(`**Date:** ${date}  `)
  lines.push(`**Duration:** ${Math.round((l.duration_seconds || 0) / 60)} min  `)
  lines.push('')
  if (l.keywords?.length) {
    lines.push('## Keywords', '')
    lines.push(l.keywords.map((k) => `\`${k}\``).join(' · '), '')
  }
  if (l.timeline?.length) {
    lines.push('## Timeline', '')
    for (const e of l.timeline) {
      const icon = e.type === 'formula' ? '🔢' : e.type === 'question' ? '❓' : e.type === 'example' ? '💡' : e.type === 'note' ? '⭐' : '📌'
      lines.push(`- **${e.t}** ${icon} ${e.event}`)
    }
    lines.push('')
  }
  lines.push('## Transcript', '')
  lines.push(l.transcript_md || '_No transcript_')
  if (l.summary) {
    lines.push('', '## Summary', '', l.summary)
  }
  lines.push('', '---', '', '_Generated by Cotton Candy_')
  return lines.join('\n')
}

export function downloadText(filename: string, content: string, mime = 'text/plain') {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

// --------- PDF export (jsPDF) — theme-aware ---------
function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '')
  const r = parseInt(h.slice(0, 2), 16)
  const g = parseInt(h.slice(2, 4), 16)
  const b = parseInt(h.slice(4, 6), 16)
  return [r, g, b]
}

export async function lectureToPdf(
  l: Lecture,
  opts: { watermark?: boolean; theme?: ThemeTokens } = {}
) {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const H = doc.internal.pageSize.getHeight()
  const M = 48
  let y = M

  const theme = opts.theme || THEMES.pink
  const pink = hexToRgb(theme.primary)        // header band
  const dark = hexToRgb(theme.dark)
  const gray = hexToRgb(theme.gray)
  const soft = hexToRgb(theme.soft)
  const accent = hexToRgb(theme.primaryDark)  // timeline bold

  const nextPage = () => { doc.addPage(); y = M }
  const ensure = (h: number) => { if (y + h > H - M) nextPage() }
  const wrap = (txt: string, maxWidth: number, fontSize: number) => {
    doc.setFontSize(fontSize)
    return doc.splitTextToSize(txt, maxWidth) as string[]
  }

  // HEADER BAND (theme primary color)
  doc.setFillColor(...pink)
  doc.rect(0, 0, W, 90, 'F')
  doc.setTextColor(...dark)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(22)
  doc.text(l.title || 'Lecture', M, 52)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(11)
  const meta: string[] = []
  if (l.subject)  meta.push(l.subject)
  if (l.lecturer) meta.push(l.lecturer)
  if (l.location) meta.push(l.location)
  meta.push(new Date(l.started_at).toLocaleDateString())
  doc.text(meta.join('  ·  '), M, 74)
  y = 120

  // KEYWORDS
  if (l.keywords?.length) {
    doc.setTextColor(...gray)
    doc.setFontSize(10)
    doc.text('KEYWORDS', M, y); y += 14
    doc.setTextColor(...dark)
    doc.setFontSize(11)
    let x = M
    for (const k of l.keywords.slice(0, 20)) {
      const w = doc.getTextWidth(k) + 14
      if (x + w > W - M) { x = M; y += 22 }
      doc.setFillColor(...soft)
      doc.roundedRect(x, y - 10, w, 18, 9, 9, 'F')
      doc.text(k, x + 7, y + 3)
      x += w + 6
    }
    y += 24
  }

  // TIMELINE
  if (l.timeline?.length) {
    ensure(60)
    doc.setTextColor(...gray)
    doc.setFontSize(10)
    doc.text('TIMELINE', M, y); y += 16
    doc.setFontSize(11)
    for (const e of l.timeline) {
      ensure(18)
      const icon = e.type === 'formula' ? '[formula]'
        : e.type === 'question' ? '[question]'
        : e.type === 'example' ? '[example]'
        : e.type === 'note' ? '[note]'
        : '[topic]'
      doc.setTextColor(...accent)
      doc.setFont('helvetica', 'bold')
      doc.text(e.t, M, y)
      doc.setTextColor(...dark)
      doc.setFont('helvetica', 'normal')
      const line = `  ${icon}  ${e.event}`
      const ls = wrap(line, W - 2 * M - 50, 11)
      for (let i = 0; i < ls.length; i++) {
        if (i === 0) doc.text(ls[i], M + 50, y)
        else { y += 14; ensure(14); doc.text(ls[i], M + 50, y) }
      }
      y += 16
    }
    y += 10
  }

  // TRANSCRIPT
  ensure(40)
  doc.setTextColor(...gray)
  doc.setFontSize(10)
  doc.text('TRANSCRIPT', M, y); y += 16
  doc.setTextColor(...dark)
  doc.setFontSize(12)
  const paragraphs = (l.transcript_md || '').split(/\n+/)
  for (const p of paragraphs) {
    if (!p.trim()) { y += 6; continue }
    const isHeading = p.startsWith('##')
    if (isHeading) {
      ensure(28)
      doc.setFont('helvetica', 'bold')
      doc.setFontSize(13)
      doc.setTextColor(...accent)
      const txt = p.replace(/^#+\s*/, '')
      const ls = wrap(txt, W - 2*M, 13)
      for (const line of ls) { ensure(18); doc.text(line, M, y); y += 18 }
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(12)
      doc.setTextColor(...dark)
      continue
    }
    const clean = p.replace(/^[-*]\s*/, '• ')
    const ls = wrap(clean, W - 2 * M, 12)
    for (const line of ls) { ensure(16); doc.text(line, M, y); y += 15 }
    y += 4
  }

  // FOOTER
  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setFontSize(9)
    doc.setTextColor(...gray)
    doc.text(`Cotton Candy${opts.watermark ? ' · upgrade to remove this line' : ''}`, M, H - 20)
    doc.text(`${i} / ${pages}`, W - M, H - 20, { align: 'right' })
  }

  doc.save(`${(l.title || 'lecture').replace(/[^\w-]+/g, '_')}.pdf`)
}

